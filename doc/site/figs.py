"""ผังวางตำแหน่งเอง (hand-laid) ของแผนภาพในเอกสาร ใช้ตัววาดใน flow_svg.py

build.py จะแทนบล็อก ```mermaid ในไฟล์ .md ด้วย SVG จากที่นี่ เมื่อหัวข้อ (heading) ที่อยู่ก่อนบล็อกนั้นขึ้นต้นด้วยคีย์ใน HEADINGS
ถ้าไม่มีคีย์ตรง บล็อก mermaid เดิมยังแสดงตามปกติ (ใช้เป็น fallback และอ่านได้บน GitHub)

วิธีแก้ผัง: ขยับชื่อโหนดใน grid (ช่องว่าง = '.'), เพิ่มโหนดใน nodes, เพิ่มเส้นใน edges
  kind: page(ฟ้า) ok(เขียว) err(แดง) sys(เทา) warn(ส้ม) dec(หกเหลี่ยม=คำถาม) end(ปลายทาง) start(เริ่ม) head(หัวคอลัมน์)
  เส้น: "A -> B : ป้าย" | "A ~> B" เส้นประ | "A -- B" ไม่มีหัวลูกศร | "A <-> B" สองหัว"""
from flow_svg import N, CARD, diagram

HEADINGS = {}   # คำขึ้นต้นของ heading -> ฟังก์ชันสร้างผัง


def fig(prefix):
    def deco(fn):
        HEADINGS[prefix] = fn
        return fn
    return deco


